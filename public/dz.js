// --- Les effets de la version DZ : bandeau défilant, pluie d'emojis, phrase d'accueil ---
(function () {
  const mk = (tag, cls, text) => { const n = document.createElement(tag); if (cls) n.className = cls; if (text !== undefined) n.textContent = text; return n; };

  // bandeau vert-blanc-rouge qui défile tout en haut
  function ribbon(on) {
    if (!document.body) return; // la page se charge encore : on réessaie à la fin du chargement
    let r = document.querySelector('.dz-ribbon');
    if (!on) { if (r) r.remove(); return; }
    if (r) return;
    r = mk('div', 'dz-ribbon'); r.setAttribute('aria-hidden', 'true'); r.setAttribute('data-notranslate', '');
    const track = mk('div', 'dz-track');
    const line = window.DZ.ribbon.join('   ✦   ') + '   ✦   ';
    track.append(mk('span', '', line), mk('span', '', line));
    r.append(track);
    document.body.prepend(r);
  }

  // pluie de drapeaux, thé et couscous quand on passe en version DZ
  window.ssDzParty = function () {
    if (document.querySelector('.dz-party')) return;
    const calm = window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches;
    const box = mk('div', 'fl-party dz-party'); box.setAttribute('aria-hidden', 'true');
    const EMO = ['🇩🇿', '☕', '🥘', '⚽', '🌙', '⭐', '🍯', '🇩🇿'];
    if (!calm) {
      for (let i = 0; i < 30; i++) {
        const f = mk('span', 'fl-p', EMO[i % EMO.length]);
        f.style.cssText = `left:${Math.random() * 100}%;font-size:${1.2 + Math.random() * 2}rem;animation-delay:${(Math.random() * 1.2).toFixed(2)}s;animation-duration:${(2.4 + Math.random() * 1.6).toFixed(2)}s;--sway:${(Math.random() * 90 - 45).toFixed(0)}px`;
        box.append(f);
      }
    }
    const card = mk('div', 'fl-card dz-card');
    card.append(mk('div', 'fl-big', '🇩🇿'), mk('b', '', 'Marhba, khoya !'), mk('p', '', 'Version DZ activée. Le thé est en route, inchallah.'));
    box.append(card);
    document.body.append(box);
    setTimeout(() => { box.classList.add('out'); setTimeout(() => box.remove(), 600); }, 3200);
  };

  // phrase d'accroche de l'accueil : une blague DZ au hasard (l'accueil l'appelle quand la langue change)
  window.ssDzPhrase = () => window.DZ.phrases[Math.floor(Math.random() * window.DZ.phrases.length)];

  const apply = (lang) => ribbon(lang === 'dz');
  window.addEventListener('ss-lang', (e) => apply(e.detail.lang));
  const start = () => apply(window.siteLang && window.siteLang());
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
})();
